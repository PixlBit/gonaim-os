import type { Brief } from "./brief.js";

/**
 * البديل الحتمي.
 *
 * بلا مفتاح لا تتعطّل الشاشة: تُعطي ما تستطيع إعطاءه بلا نموذج — ملخصًا
 * مرتبًا من نفس الوقائع. أقل جمالًا، وأكثر صدقًا، ويعمل بلا إنترنت.
 *
 * وهذا هو الاختبار الحقيقي للتصميم: لو كانت الميزة تنهار بلا النموذج،
 * فالنموذج ليس طبقة إضافية — هو المنتج. وهنا ليس كذلك.
 */
export function offline(brief: Brief): string {
  const facts = brief.text.trim();
  const head: Record<Brief["kind"], string> = {
    letter: "ملخص الشهر — من غير أي تفسير، ده اللي اتسجّل:",
    advice: "الفروق المعلنة والملاحَظة بينكم، زي ما هي:",
    gift: "اللي كتبه عن نفسه، واللي نفسه يعمله:",
    week: "أسبوعكم الجاي كما هو مكتوب:",
    story: "الذكرى زي ما اتسجّلت:",
  };
  return `${head[brief.kind]}\n\n${facts}\n\n` +
    "— الصيغة دي حتمية: من غير مفتاح النموذج، المنصة بتعرض الوقايع من غير ما تكتب حواليها.";
}
