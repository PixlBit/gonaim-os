-- إضافة طبقة Whisper إلى signal_tier.
--
-- Expansion §10.2 تعرّف خمس طبقات اقتراح: Whisper · Nudge · Window ·
-- Interrupt · Block. الملاحظة الصغيرة داخل السياق هي أخف تدخل ممكن،
-- وإسقاطها يجعل أقل ما يستطيع النظام فعله هو "الاقتراح" — وهو ما يكسر
-- مبدأ الهدوء في §5.4.
--
-- تقف وحدها في هجرة منفصلة عمدًا: Postgres يمنع استخدام قيمة enum جديدة
-- داخل المعاملة التي أضافتها. الجداول التي تستعملها تأتي في الهجرة التالية،
-- بعد أن تكون هذه قد أُودعت.

alter type signal_tier add value if not exists 'whisper' before 'nudge';
